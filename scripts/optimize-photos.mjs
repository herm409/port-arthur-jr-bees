function widthsFor(sourceWidth) {
  const widths = TARGETS.filter((w) => w <= sourceWidth);
  if (sourceWidth < 1600 && !widths.includes(sourceWidth)) widths.push(sourceWidth);
  return widths.sort((a, b) => a - b);
}

await mkdir(OUT, { recursive: true });

const catalog = {};

for (const file of FILES) {
  const input = path.join(SRC, file);
  if (!existsSync(input)) {
    console.error("missing original", input);
    process.exit(1);
  }
  const id = file.replace(/\.jpg$/i, "");
  const meta = await sharp(input).rotate().metadata();
  const srcW = meta.width ?? 0;
  const srcH = meta.height ?? 0;
  if (!srcW || !srcH) {
    console.error("no dimensions", file);
    process.exit(1);
  }
  const widths = widthsFor(srcW);
  catalog[id] = { width: srcW, height: srcH, widths };

  for (const width of widths) {
    const height = Math.round((srcH / srcW) * width);
    const base = path.join(OUT, `${id}-w${width}`);
    const pipeline = () =>
      sharp(input)
        .rotate()
        .resize({ width, height, fit: "inside", withoutEnlargement: true });

    await pipeline().avif({ quality: 48, effort: 4 }).toFile(`${base}.avif`);
    await pipeline().webp({ quality: 72 }).toFile(`${base}.webp`);
    await pipeline().jpeg({ quality: 78, mozjpeg: true }).toFile(`${base}.jpg`);
  }
  console.log(id, srcW + "x" + srcH, widths.join(","));
}

const ts = `/* Generated by scripts/optimize-photos.mjs. Do not edit by hand. */\nexport const photoSizes = ${JSON.stringify(catalog, null, 2)} as const;\n`;
await writeFile(path.join(ROOT, "src/lib/photo-sizes.ts"), ts);
console.log("wrote src/lib/photo-sizes.ts");
